        /// <summary>An assumption applies to both cohorts alike, so it is written once per column, unformatted.</summary>
        private static void AddAssumptionRow(XlsxSheet sheet, string measure, double value, string notes)
        {
            AddAssumptionRow(sheet, measure, value, 2, notes);
        }

        /// <summary>An assumption written once for each of <paramref name="cohorts"/> columns, unformatted.</summary>
        private static void AddAssumptionRow(XlsxSheet sheet, string measure, double value, int cohorts, string notes)
        {
            var cells = new List<object> { measure };
            for (var i = 0; i < cohorts; i++)
            {
                cells.Add(value);
            }
            cells.Add(XlsxCell.Wrapped(notes));
            sheet.AddRow(cells.ToArray());
        }

        /// <summary>
        /// Every cohort's assumptions as one list. They differ only in the sentence naming how many people
        /// the volumes were observed for, so each sentence is written once, in order, with the other
        /// cohorts' versions beside the first where they differ.
        /// </summary>
        private static IEnumerable<string> MergeAssumptions(params IList<string>[] cohorts)
        {
            var written = new HashSet<string>(StringComparer.Ordinal);
            var count = cohorts.Max(list => list?.Count ?? 0);

            for (var i = 0; i < count; i++)
            {
                foreach (var list in cohorts)
                {
                    if (list == null || i >= list.Count) continue;
                    if (written.Add(list[i])) yield return list[i];
                }
            }
        }

        private static string Num(double value)
        {
            return value.ToString("0.###############", CultureInfo.InvariantCulture);
        }

        private static void WriteOpportunitiesSheet(XlsxWriter workbook, CopilotAdoptionAnalysis analysis)
        {
            var candidates = analysis.Opportunities ?? new List<LicenceOpportunityRow>();
            if (candidates.Count == 0) return;

            var sheet = workbook.AddSheet("Licence opportunities");
            var summary = analysis.Summary;
            var cap = RowCap(summary);

            if (candidates.Count > cap)
            {
                sheet.AddTitle("Licence opportunities - TRUNCATED");
                sheet.AddRow(XlsxCell.Wrapped(
                    $"This sheet lists the {cap:N0} strongest of {candidates.Count:N0} candidates, "
                    + "proven-demand candidates first so recurrent unlicensed Copilot users cannot be truncated "
                    + "away by people who have never used it. The headline 'recommended for a licence' figure "
                    + "covers all of them."));
                sheet.AddBlankRow();
            }
            else if (summary.FiguresIncomplete)
            {
                sheet.AddTitle("Licence opportunities - FIGURES INCOMPLETE");
                sheet.AddRow(XlsxCell.Wrapped(
                    "A source query failed or timed out. This sheet is incomplete and must not be used as a complete employee list."));
                sheet.AddBlankRow();
            }

            // Proven demand first, then score - the same order the service and the CSV use. Re-sorting on
            // score alone here would undo it precisely where it matters most: this sheet TRUNCATES, and a
            // proven-demand candidate can score below the recommendation bar by construction (the Copilot
            // weight sits under it), so a large tenant's workbook would drop people who already use
            // Copilot in favour of people who never have.
            var listed = candidates
                .OrderBy(c => c.QualificationTier == CopilotAdoptionScoring.OpportunityTiers.ProvenDemand ? 0 : 1)
                .ThenByDescending(c => c.OpportunityScore)
                .ThenBy(c => c.UserPrincipalName, StringComparer.OrdinalIgnoreCase)
                .Take(cap);

            WriteRowsFromColumns(
                sheet,
                listed,
                CopilotAdoptionExports.LicenceOpportunityColumns(summary.FiguresIncomplete, WarningSummary(summary)),
                new List<CsvColumn<LicenceOpportunityRow>>
                {
                    // Workbook-only: the two collaboration figures added together, because the reader of a
                    // purchase case wants one "how busy is this person" number, and the guidance links for
                    // the single action every row on this sheet shares.
                    new CsvColumn<LicenceOpportunityRow>("Teams total", r => r.TeamsMessages + r.TeamsMeetings),
                    new CsvColumn<LicenceOpportunityRow>("Email total", r => r.EmailsSent + r.EmailsRead),
                    new CsvColumn<LicenceOpportunityRow>("Microsoft guidance resources",
                        r => CopilotAdoptionGuidanceCatalogue.TitlesForAction(CopilotAdoptionGuidanceCatalogue.UnlicensedActionCode)),
                    new CsvColumn<LicenceOpportunityRow>("Microsoft guidance URLs",
                        r => CopilotAdoptionGuidanceCatalogue.UrlsForAction(CopilotAdoptionGuidanceCatalogue.UnlicensedActionCode)),
                });
        }

        /// <summary>
        /// The modelled licence estimate, on its own sheet beside the candidate list it sizes.
