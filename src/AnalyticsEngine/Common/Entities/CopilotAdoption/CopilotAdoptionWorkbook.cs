        /// <para>Reflected over <see cref="CopilotAdoptionOptions"/> for the same reason as the facts
        /// sheet: an option added later is covered without anyone remembering to come back here.</para>
        /// </summary>
        private static void WriteSettingsSheet(
            XlsxWriter workbook,
            CopilotAdoptionOptions configured,
            CopilotAdoptionOptions model)
        {
            var sheet = workbook.AddSheet("Settings");
            sheet.SetColumnWidths(46, 26, 46);

            sheet.AddTitle("Settings used to produce this snapshot");
            sheet.AddRow(XlsxCell.Wrapped(
                "Every tuning value the scoring used, keyed by its stable serialised name. Two snapshots are "
                + "only comparable if this sheet is identical in both - otherwise a change in a headline "
                + "figure may be nothing more than a moved threshold. Compare this sheet between two files "
                + "before subtracting anything on the others."));
            sheet.AddBlankRow();
            sheet.AddHeaderRow("Setting", "Value", "Property");

            var headerRow = sheet.CurrentRow;

            // The reader's own time-saved figures replace the defaults in the Value column, and the label
            // says so. Annotated in place rather than with an extra row, so every export has the same rows
            // in the same order and a lookup written against one file resolves against the next.
            var customised = !ReferenceEquals(configured, model);
            var defaults = customised
                ? ScalarFacts(configured).ToDictionary(f => f.Key, f => FactText(f.Value), StringComparer.Ordinal)
                : null;

            foreach (var setting in ScalarFacts(model))
            {
                var label = setting.Label;
                if (customised
                    && defaults.TryGetValue(setting.Key, out var byDefault)
                    && !string.Equals(byDefault, FactText(setting.Value), StringComparison.Ordinal))
                {
                    label += " - entered in the portal for this export; the product default is " + byDefault;
                }

                sheet.AddRow(setting.Key, setting.Value, label);
            }

            sheet.FreezeTopRows(headerRow);
        }

        private static string FactText(object value)
        {
            return Convert.ToString(value, CultureInfo.InvariantCulture) ?? string.Empty;
        }

        /// <summary>One flattened <c>key | value | label</c> row of a reflected object.</summary>
        private class ScalarFact
        {
            public string Key { get; set; }

            public object Value { get; set; }

            public string Label { get; set; }
        }

        /// <summary>
        /// Flattens the readable scalar properties of an object into stable, sorted key/value rows.
        ///
        /// <para>The key is the <see cref="JsonPropertyAttribute"/> name where there is one, so it matches
        /// what the API returns and stays stable if the C# property is ever renamed. Sorting is ordinal on
        /// that key: reflection does not guarantee declaration order, and an export whose row order can
        /// shift between runs is useless for the one job this sheet has.</para>
        ///
        /// <para>A property that throws is skipped rather than being allowed to lose the whole export -
        /// the same bargain <c>CsvSerialiser.SafeValue</c> makes, and for the same reason.</para>
        /// </summary>
        private static IEnumerable<ScalarFact> ScalarFacts(object source)
        {
            if (source == null) return Enumerable.Empty<ScalarFact>();

            var facts = new List<ScalarFact>();

            foreach (var property in source.GetType().GetProperties(BindingFlags.Public | BindingFlags.Instance))
            {
                if (!property.CanRead || property.GetIndexParameters().Length > 0) continue;

                // Deliberately excluded rather than overlooked: a property the API does not serialise is
                // an internal assembly detail of how the summary is built, not a measure. SourceWarnings
                // is the live example - its contents are already merged into Warnings, so writing it here
                // would duplicate every warning under a second name and make the sheets disagree.
                if (property.GetCustomAttribute<JsonIgnoreAttribute>() != null) continue;

                object value;
                try
                {
                    value = property.GetValue(source);
                }
                catch (Exception)
                {
                    continue;
                }

                var key = property.GetCustomAttribute<JsonPropertyAttribute>()?.PropertyName ?? property.Name;
                var type = Nullable.GetUnderlyingType(property.PropertyType) ?? property.PropertyType;

                if (IsScalar(type))
                {
                    facts.Add(new ScalarFact { Key = key, Value = ScalarCell(value), Label = property.Name });
                }
                else if (typeof(ICollection).IsAssignableFrom(type))
                {
                    // The count, not the contents. A list that emptied between two snapshots is a real
                    // finding and would otherwise be invisible here.
                    //
                    // Keyed off the PROPERTY TYPE, never off the runtime value. Testing `value is
                    // ICollection` would silently drop the row whenever the list happened to be null,
                    // which is the one thing this sheet must never do: a row that appears in one export
                    // and not the other shifts every row below it and misaligns the diff the whole sheet
                    // exists for. A null list is written blank - unknown, not zero - exactly like a null
                    // scalar.
                    var collection = value as ICollection;
                    facts.Add(new ScalarFact
                    {
                        Key = key + ".count",
                        Value = collection == null ? (object)string.Empty : collection.Count,
                        Label = property.Name + " (row count)",
                    });
                }
            }

            return facts.OrderBy(f => f.Key, StringComparer.Ordinal).ToList();
        }

        private static bool IsScalar(Type type)
        {
            return type.IsPrimitive
                   || type.IsEnum
                   || type == typeof(string)
                   || type == typeof(decimal)
                   || type == typeof(DateTime);
        }

        /// <summary>
        /// Renders a reflected value as a cell, keeping it typed so Excel can sort and subtract it.
        ///
        /// <para>A null stays empty. It must never become zero: across this report a null means "not
        /// reported" or "not attributable", and a zero in a file whose purpose is comparison would be
        /// read as a measured decline.</para>
        /// </summary>
        private static object ScalarCell(object value)
        {
            switch (value)
            {
                case null:
                    return string.Empty;
                case bool b:
                    return YesNo(b);
                case DateTime dt:
                    return XlsxCell.Date(dt);
                case Enum e:
                    return e.ToString();
                default:
                    return value;
            }
        }

        #endregion

        #region Per-user sheets

        /// <summary>
        /// Writes a per-user table from the same <see cref="CsvColumn{T}"/> definitions the CSV export
        /// uses, optionally followed by extra columns that only make sense in a workbook.
        ///
        /// <para>Sharing the column definitions is the point. The workbook used to declare its own
        /// headers, and the two drifted until the Licensed users sheet was missing twenty-eight of the
        /// columns its CSV already had - including the reclaim eligibility that a headline figure on the
        /// first sheet is counted from. The drift was silent because nothing compared them. Now there is
        /// one definition and a test that fails if a sheet does not carry all of it.</para>
        ///
        /// <para>Values are written typed rather than pre-formatted: a date stays a date and a number
        /// stays a number, so the auto-filter sorts chronologically and numerically instead of
        /// alphabetically. This is why <c>CsvSerialiser.Format</c> is not reused - it renders everything
        /// to a string, which is right for a CSV and wrong here.</para>
        ///
        /// <para>It also deliberately does NOT copy the CSV's formula-injection guard. That guard exists
        /// because a spreadsheet parses a CSV cell beginning <c>=</c>, <c>+</c>, <c>-</c> or <c>@</c> as a
        /// formula; a string cell in an xlsx part is never evaluated, so prefixing here would achieve
        /// nothing except putting a stray apostrophe in front of every negative number and every
        /// hyphen-led department name.</para>
        /// </summary>
        private static void WriteRowsFromColumns<T>(
            XlsxSheet sheet,
            IEnumerable<T> rows,
            IReadOnlyList<CsvColumn<T>> columns,
            IReadOnlyList<CsvColumn<T>> extraColumns = null,
            bool setColumnWidths = true,
            bool freezePanes = true)
        {
            var all = CombineColumns(columns, extraColumns);

            if (setColumnWidths) sheet.SetColumnWidths(all.Select(ColumnWidth).ToArray());
            sheet.AddHeaderRow(all.Select(c => c.Header).ToArray());

            var headerRow = sheet.CurrentRow;

            foreach (var row in rows)
            {
                sheet.AddRow(all.Select(c => RowCell(c, row)).ToArray());
            }

            if (freezePanes) sheet.FreezeTopRows(headerRow);
            sheet.AddAutoFilter(headerRow, sheet.CurrentRow, 1, all.Count);
        }

        private static List<CsvColumn<T>> CombineColumns<T>(
            IReadOnlyList<CsvColumn<T>> columns,
            IReadOnlyList<CsvColumn<T>> extraColumns)
        {
            var all = new List<CsvColumn<T>>(columns);
            if (extraColumns != null) all.AddRange(extraColumns);
            return all;
        }

        /// <summary>
        /// How many per-user rows this workbook may write, from the analysis's own options so a tenant
        /// that wants its whole population in one file can have it without a rebuild.
        /// </summary>
        private static int RowCap(CopilotAdoptionSummary summary)
        {
            return summary?.Options?.WorkbookUserRows ?? DefaultMaxUserRows;
        }

        /// <summary>
        /// Reads one cell, turning an accessor failure into an empty cell rather than a failed export.
        /// A whole workbook should not be lost to one null navigation property.
        /// </summary>
        private static object RowCell<T>(CsvColumn<T> column, T row)
        {
            object value;
            try
            {
                value = column.Value(row);
            }
            catch (NullReferenceException)
            {
                return string.Empty;
            }

            switch (value)
            {
                case null:
                    return string.Empty;
                case bool b:
                    return YesNo(b);
                case DateTime dt:
                    return XlsxCell.Date(dt);
                case string s:
                    // Prose - a rationale, a recommended action, an exclusion note - needs wrapping or it
                    // spills across the neighbouring columns and the sheet is unreadable.
                    return s.Length > 60 ? XlsxCell.Wrapped(s) : (object)s;
                default:
                    return value;
            }
        }

        /// <summary>
        /// A column width guessed from the heading. Crude on purpose: these sheets are now fifty
        /// columns wide, a hand-maintained width array would be one more thing to drift out of step with
        /// the column list, and nothing about the report depends on the widths being exact.
        /// </summary>
        private static double ColumnWidth<T>(CsvColumn<T> column)
        {
            var header = column.Header ?? string.Empty;

            if (header.IndexOf("Justification", StringComparison.OrdinalIgnoreCase) >= 0
                || header.IndexOf("detail", StringComparison.OrdinalIgnoreCase) >= 0
                || header.IndexOf("reason", StringComparison.OrdinalIgnoreCase) >= 0
                || header.IndexOf("note", StringComparison.OrdinalIgnoreCase) >= 0
                || header.IndexOf("warnings", StringComparison.OrdinalIgnoreCase) >= 0
                || header.IndexOf("guidance", StringComparison.OrdinalIgnoreCase) >= 0
                || header.IndexOf("comparison", StringComparison.OrdinalIgnoreCase) >= 0)
            {
                return 60;
            }

            if (header.IndexOf("principal name", StringComparison.OrdinalIgnoreCase) >= 0
                || header.IndexOf("email", StringComparison.OrdinalIgnoreCase) >= 0
                || header.IndexOf("manager", StringComparison.OrdinalIgnoreCase) >= 0)
            {
                return 34;
            }

            return Math.Max(14, Math.Min(30, header.Length + 4));
        }

        #endregion

        private static double Percentage(double part, double total)
        {
            return total <= 0 ? 0 : Math.Round(part / total * 100d, 1, MidpointRounding.AwayFromZero);
        }
