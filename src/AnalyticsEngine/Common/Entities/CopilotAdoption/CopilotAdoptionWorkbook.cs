                    // into something the reader can act on without going back to the portal.
                    new CsvColumn<LicensedUserAdoptionRow>("Source comparison", r => SourceComparisonSummary(r, summary)),
                    new CsvColumn<LicensedUserAdoptionRow>("Microsoft guidance resources",
                        r => CopilotAdoptionGuidanceCatalogue.TitlesForAction(r.RecommendedActionCode)),
                    new CsvColumn<LicensedUserAdoptionRow>("Microsoft guidance URLs",
                        r => CopilotAdoptionGuidanceCatalogue.UrlsForAction(r.RecommendedActionCode)),
                });
        }

