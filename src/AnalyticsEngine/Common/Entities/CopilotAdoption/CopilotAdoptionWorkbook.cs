        /// <summary>
        /// Plain-English names for the sections that stay tenant-wide when the report is narrowed to
        /// one email domain, so the Report sheet can name them rather than quote internal codes.
        /// </summary>
        private static string DescribeUnscopedSections(IEnumerable<string> sections)
        {
            var labels = (sections ?? Enumerable.Empty<string>())
                .Select(UnscopedSectionLabel)
                .Where(l => !string.IsNullOrWhiteSpace(l))
                .ToList();

            if (labels.Count == 0) return string.Empty;
            if (labels.Count == 1) return labels[0];

            return string.Join(", ", labels.Take(labels.Count - 1)) + " and " + labels[labels.Count - 1];
        }

        private static string UnscopedSectionLabel(string section)
        {
            switch (section)
            {
                case CopilotAdoptionUnscopedSections.UsageByApp: return "Copilot use by app";
                case CopilotAdoptionUnscopedSections.TopResourceTypes: return "the resource-type breakdown";
                case CopilotAdoptionUnscopedSections.WeeklyTrend: return "the weekly trend";
                case CopilotAdoptionUnscopedSections.Agents: return "the agent inventory";
                case CopilotAdoptionUnscopedSections.PurchasedSeats: return "purchased and unassigned seats";
                case CopilotAdoptionUnscopedSections.CoworkCredits: return "the Cowork credit balance";
                case CopilotAdoptionUnscopedSections.MicrosoftReport: return "Microsoft's usage-report figures";
                default: return section;
            }
        }

        /// <summary>The cover sheet's "Population" value: whose figures this file holds.</summary>
        private static string PopulationLabel(CopilotAdoptionSummary summary)
        {
            var hasDomain = !string.IsNullOrWhiteSpace(summary.ScopedEmailDomain);
            var filterDescription = FilterDescription(summary);
            var hasFilter = !string.IsNullOrWhiteSpace(filterDescription);

            if (hasDomain && hasFilter)
            {
                return "Email domain " + summary.ScopedEmailDomain + ", people where " + filterDescription;
            }

            if (hasDomain) return "Email domain " + summary.ScopedEmailDomain;
            if (hasFilter) return "People where " + filterDescription;
            return "Whole tenant";
        }

        /// <summary>
        /// Every people filter applied, in plain English: the administrator's global filter, named as such,
        /// and the reader's own. Each is bracketed when it has OR groups, so the "and" joining them cannot be
        /// read as binding tighter than the groups inside either.
        /// </summary>
        internal static string FilterDescription(CopilotAdoptionSummary summary)
        {
            var user = summary.UserFilterDescription;
            var global = summary.GlobalFilterDescription;

            if (string.IsNullOrWhiteSpace(global)) return user;

            var globalPart = Bracket(global) + " (set by a portal administrator)";
            return string.IsNullOrWhiteSpace(user) ? globalPart : globalPart + " and " + Bracket(user);
        }

        private static string Bracket(string description)
        {
            return description.IndexOf(" or ", StringComparison.Ordinal) >= 0 ? "(" + description + ")" : description;
        }

        private static string PopulationNote(CopilotAdoptionSummary summary)
        {
            var hasDomain = !string.IsNullOrWhiteSpace(summary.ScopedEmailDomain);
            var hasFilter = !string.IsNullOrWhiteSpace(FilterDescription(summary));

            if (!hasDomain && !hasFilter) return "Every Copilot seat holder the analysis could see.";

            // The licence holders the filter selects include any the capped analysis never reached - its
            // scopedLicensedUsersNotAnalysed warning counts them - or this row and "Users analysed" below
            // would disagree about how many people are in the filter.
            var notAnalysedInView = LicenceHoldersNotAnalysed(summary);
            var of = summary.UnscopedLicensedUsers.HasValue
                ? string.Format(
                    CultureInfo.InvariantCulture,
                    " {0:N0} of the tenant's {1:N0} Copilot licence holders are in it.",
                    summary.LicensedUsers + notAnalysedInView,
                    summary.UnscopedLicensedUsers.Value)
                  + (notAnalysedInView > 0
                      ? string.Format(
                          CultureInfo.InvariantCulture,
                          " {0:N0} of them are beyond the analysis limit and are left out of every figure.",
                          notAnalysedInView)
                      : string.Empty)
                : string.Empty;

            return (hasFilter
                    ? "Only the people matching the filter, judged on their Entra ID attributes and custom organisations as last imported."
                    : "Only the people whose sign-in name is on this domain.")
                + of
                + " Sections listed as tenant-wide above are the exception.";
        }

