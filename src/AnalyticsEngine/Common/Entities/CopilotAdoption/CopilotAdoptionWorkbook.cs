    /// <summary>
    /// Renders a complete Copilot adoption analysis as an Excel workbook - every figure, table and
    /// chart that is on screen, with the charts live and bound to the cells rather than pasted in as
    /// pictures.
    ///
    /// The purpose is the point-in-time snapshot. A screenshot of a dashboard cannot be compared with
    /// another screenshot six months later: the numbers cannot be subtracted, the definitions may have
    /// moved, and nobody can tell which period either was run over. A workbook can - the run metadata,
    /// the product build and every threshold used are written into the Report sheet, so two files taken
    /// before and after an enablement programme are directly comparable and the reader can prove the
    /// comparison is fair.
    ///
    /// <para>Two sheets exist purely to make that comparison mechanical rather than manual. "Snapshot
    /// facts" carries every scalar figure as a stable <c>key | value</c> row, and "Settings" carries
    /// every tuning option the same way. Both are generated by reflection over
    /// <see cref="CopilotAdoptionSummary"/> and <see cref="CopilotAdoptionOptions"/>, so a measure added
    /// later cannot quietly fail to reach the file - which is exactly how the per-user sheets came to
    /// be missing twenty-eight of the columns their CSV equivalents already carried.</para>
    ///
    /// <para>The per-user sheets are rendered from the same <see cref="CsvColumn{T}"/> definitions the
    /// CSV exports use, so the two can never disagree about what a row contains.</para>
    ///
    /// Built from the same cached analysis the API serves the screen from, so the workbook can never
    /// quietly disagree with the page it was downloaded from.
    /// </summary>
    public static class CopilotAdoptionWorkbook
    {
        /// <summary>
        /// Rows of a per-user list written to the workbook before it is truncated, when the analysis
        /// does not carry its own <see cref="CopilotAdoptionOptions.MaxWorkbookUserRows"/>.
        /// </summary>
        public const int DefaultMaxUserRows = 20000;

        /// <summary>
        /// Ceiling for a configured row cap. A worksheet holds 1,048,576 rows and these sheets spend a
        /// few on banners, headers and a frozen pane, so this sits below the hard limit rather than on
        /// it: a file Excel refuses to open is a worse outcome than a truncated sheet that says so.
        /// </summary>
        public const int MaxSupportedUserRows = 1000000;

        /// <summary>
        /// What a workbook exported without the See PII permission says where the individual rows would be.
        /// </summary>
        internal const string IndividualDataWithheld = "not included (needs the See PII permission)";

        /// <summary>Builds the workbook and returns it as a byte array ready to stream to the browser.</summary>
        /// <param name="analysis">The cached analysis the page was rendered from. Never modified.</param>
        /// <param name="timeSaved">
        /// The reader's own time-saved assumptions from the portal, or null for the configured defaults.
        /// They change the two modelled estimate sheets and the matching rows of the Settings sheet and
        /// nothing else: no measured figure depends on them.
        /// </param>
        /// <param name="includeIndividualData">
        /// False for a reader without the portal's See PII permission (#661). The Licensed users and
        /// Licence opportunities sheets are left out, the Cowork readiness sheet keeps its aggregate
        /// sections but not its candidate list, and the accountability roll-up is left out when its rows
        /// are managers - see <see cref="CopilotAdoptionSummary.WithoutIndividualData"/>. An export is
        /// never less redacted than the screen it came from.
        /// </param>
        public static byte[] Build(CopilotAdoptionAnalysis analysis, TimeSavedOverrides timeSaved = null, bool includeIndividualData = true)
        {
            if (analysis == null) throw new ArgumentNullException(nameof(analysis));

            using (var workbook = new XlsxWriter())
            {
                var summary = includeIndividualData ? analysis.Summary : analysis.Summary.WithoutIndividualData();
                var configured = summary.Options ?? CopilotAdoptionOptions.Default;
                var modelOptions = timeSaved != null && timeSaved.Any ? timeSaved.ApplyTo(configured) : configured;

                WriteReportSheet(workbook, summary, includeIndividualData);
                WriteHeadlineSheet(workbook, summary);
                WriteFunnelSheet(workbook, summary);
                WriteEngagementSheet(workbook, summary);
                WriteTrendSheet(workbook, summary);
                WriteDepartmentSheet(workbook, summary);
                WriteEmailDomainSheet(workbook, summary);
                WriteAgentSheet(workbook, summary);
                WriteUnlicensedSheet(workbook, summary);
                WriteActionPlanSheet(workbook, summary);
                if (includeIndividualData) WriteLicensedUsersSheet(workbook, analysis);
                WriteCoworkSheet(workbook, analysis, includeIndividualData);
                WriteCoworkEstimateSheet(workbook, summary, configured, modelOptions);
                WriteSeatHolderTimeSavedSheet(workbook, summary, configured, modelOptions);
                if (includeIndividualData) WriteOpportunitiesSheet(workbook, analysis);
                WriteLicenceEstimateSheet(workbook, summary, configured, modelOptions);
                WriteMethodSheet(workbook, summary, includeIndividualData);
                WriteSnapshotFactsSheet(workbook, summary);
                WriteRunDiagnosticsSheet(workbook, summary);
                WriteSettingsSheet(workbook, configured, modelOptions);

                return workbook.ToArray();
            }
        }

        /// <summary>
        /// File name carrying the period and the run date, so two snapshots never collide - and saying
        /// when the file holds a filtered population, because a file name survives forwarding where the
        /// cover sheet's warning may never be opened.
        /// </summary>
        public static string FileName(CopilotAdoptionSummary summary)
        {
            var generated = summary?.GeneratedUtc ?? DateTime.UtcNow;
            var windowDays = summary?.WindowDays ?? 0;
            var narrowed = summary != null && !string.IsNullOrWhiteSpace(FilterDescription(summary)) ? "-filtered" : string.Empty;

            return string.Format(
                CultureInfo.InvariantCulture,
                summary?.Options?.UsesExplicitDates == true
                    ? "copilot-adoption-{3:yyyy-MM-dd}-to-{4:yyyy-MM-dd}{2}-{1:yyyy-MM-dd}.xlsx"
                    : "copilot-adoption-{0}d{2}-{1:yyyy-MM-dd}.xlsx",
                windowDays,
                generated,
                narrowed,
                summary?.FromUtc ?? generated,
                summary?.ToUtc ?? generated);
        }

        #region Report metadata

        /// <summary>
        /// The cover sheet: what this file is, what it covers, and every threshold used to produce it.
        ///
        /// The thresholds are the important part. Two snapshots are only comparable if they were
        /// scored by the same rules, and this is what lets a reader confirm that rather than assume
        /// it - the tuning is adjustable, so "adoption went up" could otherwise mean "the bar moved".
        /// </summary>
        private static void WriteReportSheet(XlsxWriter workbook, CopilotAdoptionSummary summary, bool includeIndividualData)
        {
            var sheet = workbook.AddSheet("Report");
            sheet.SetColumnWidths(42, 34, 60);

            var hasDomain = !string.IsNullOrWhiteSpace(summary.ScopedEmailDomain);
            var filterDescription = FilterDescription(summary);
            var hasFilter = !string.IsNullOrWhiteSpace(filterDescription);

            sheet.AddTitle(hasDomain
                ? "Microsoft 365 Copilot - adoption report for " + summary.ScopedEmailDomain
                : hasFilter
                    ? "Microsoft 365 Copilot - adoption report (filtered)"
                    : "Microsoft 365 Copilot - adoption report");
            sheet.AddBlankRow();

            // A spreadsheet outlives the screen it was exported from and gets forwarded without that
            // context. A file narrowed to one of several organisations in a tenant has to say so on its
            // own first sheet, or it will be read - and quoted in a licence negotiation - as the whole
            // tenant's position.
            if (hasDomain || hasFilter)
            {
                var narrowedTo = hasDomain && hasFilter
                    ? "NARROWED TO ONE EMAIL DOMAIN: " + summary.ScopedEmailDomain + ", AND FILTERED TO PEOPLE WHERE: "
                      + filterDescription + ". Every figure in this workbook describes those people only"
                    : hasDomain
                        ? "NARROWED TO ONE EMAIL DOMAIN: " + summary.ScopedEmailDomain + ". Every figure in this "
                          + "workbook describes the people on that domain only"
                        : "FILTERED TO PEOPLE WHERE: " + filterDescription + ". Every figure in this "
                          + "workbook describes those people only";

                sheet.AddRow(XlsxCell.Wrapped(
                    narrowedTo
                    + ", and must not be quoted as a tenant-wide figure."
                    + (summary.UnscopedSections.Count > 0
                        ? " The following sections could not be narrowed and remain TENANT-WIDE, because they "
                          + "come from totals that carry no per-person detail: "
                          + DescribeUnscopedSections(summary.UnscopedSections) + "."
                        : string.Empty)));

                // A condition on an organisation type deleted or disabled since the filter was built
                // matches nobody. Said here, because otherwise a file showing zero people reads as a
                // measured empty population rather than as a filter that could not be applied.
                var unknown = (summary.UserFilter?.UnknownDimensions ?? new List<string>())
                    .Concat(summary.GlobalFilter?.UnknownDimensions ?? new List<string>())
                    .Distinct(StringComparer.Ordinal)
                    .ToList();
                if (unknown.Count > 0)
                {
                    sheet.AddRow(XlsxCell.Wrapped(
                        "THE FILTER NAMES ATTRIBUTES THAT NO LONGER EXIST: " + string.Join(", ", unknown)
                        + ". An organisation type deleted or disabled after the filter was built matches nobody, "
                        + "so any figure that depends on those conditions describes nobody rather than a measured "
                        + "population. Remove the conditions, or re-create the organisation type, and export again."));
                }

                sheet.AddBlankRow();
            }

            sheet.AddHeaderRow("Property", "Value", "Notes");
            AddMeta(sheet, "Product build", BuildConstants.BuildLabel, BuildLabelNote);
            AddMeta(sheet, "Population", PopulationLabel(summary), PopulationNote(summary));
            AddMeta(sheet, "Generated (UTC)", summary.GeneratedUtc,
                "Take a snapshot before an enablement programme and another afterwards; the two files are directly comparable.");
            AddMeta(sheet, "Period covered", $"{summary.WindowDays} days",
                "All 'this period' figures use this window.");
            AddMeta(sheet, "Users analysed", summary.ScoredUsers, UsersAnalysedReportNote(summary));
            AddMeta(sheet, "From (UTC)", summary.FromUtc, string.Empty);
            AddMeta(sheet, "To (UTC)", summary.ToUtc, string.Empty);
            AddMeta(sheet, "History window", $"{summary.Options.HistoryDays} days",
                "How far back 'ever used Copilot' looks, which is what separates Dormant from Never used.");
            AddMeta(sheet, "Microsoft guidance catalogue", summary.GuidanceCatalogueVersion,
                "Version of the Microsoft-published guidance links attached to recommended actions in this workbook.");
            AddMeta(sheet, "Figures incomplete", YesNo(summary.FiguresIncomplete),
                summary.FiguresIncomplete
                    ? "A source query failed or timed out. Treat every individual row and aggregate in this workbook as incomplete."
                    : "No headline-source query reported an incomplete result.");
            if (summary.FiguresIncomplete && summary.IncompleteReasons.Count > 0)
            {
                AddMeta(sheet, "Why figures are incomplete", string.Join(" | ", summary.IncompleteReasons),
                    "The named steps did not return. Anything derived from them is a floor, not a total.");
            }
            AddMeta(sheet, "Accountability grouped by", summary.AccountabilityDimension,
                "The organisational field the accountability roll-up is grouped by. Two snapshots grouped differently are not comparable on that sheet.");
            if (includeIndividualData)
            {
                AddMeta(sheet, "Individual rows", summary.Options == null ? string.Empty : "See per-user sheets",
                    "The Licensed users, Cowork readiness and Licence opportunities sheets carry individual-level "
                    + "governance data - sign-in name, email address, email domain, office, company, country, manager, "
                    + "and who excluded a seat from reclaim and when. Do not share externally without a legal basis.");
            }
            else
            {
                // Said on the cover sheet, because a reader comparing this file with one exported by a
                // colleague who holds the permission would otherwise take the missing sheets for missing data.
                var pastRange = summary.Options?.UsesExplicitDates == true;
                AddMeta(sheet, "Individual rows", pastRange ? "not included (historical range)" : IndividualDataWithheld,
                    pastRange
                        ? "Historical ranges hide named reclaim and recommendation lists, even for readers with See PII, because they describe people and managers as they are today. The Licensed users and Licence opportunities sheets, the Cowork candidate list and any roll-up labelled with a manager's name are left out. Every aggregate figure still covers the selected population."
                        : "Exported without the portal's See PII permission, so this workbook describes groups only. The "
                          + "Licensed users and Licence opportunities sheets, the Cowork candidate list and any roll-up "
                          + "labelled with a manager's name are left out. Every aggregate figure still covers the whole population.");
            }

            sheet.AddBlankRow();
            sheet.AddHeaderRow("Data source", "Available", "Notes");
            AddMeta(sheet, "Copilot audit log", YesNo(summary.DataSources.AuditAvailable),
                "Covers every user including unlicensed Copilot Chat, and matches the period exactly.");
            AddMeta(sheet, "Microsoft Copilot usage report", YesNo(summary.DataSources.CopilotUsageReportAvailable),
                summary.DataSources.CopilotUsageReportDate.HasValue
                    ? $"Snapshot of {summary.DataSources.CopilotUsageReportDate.Value:yyyy-MM-dd}. Licensed users only."
                    : "Not imported.");
            AddMeta(sheet, "Microsoft Copilot usage report - tenant summary", YesNo(summary.MicrosoftReportDate.HasValue),
                summary.MicrosoftReportDate.HasValue
                    ? $"Microsoft's tenant totals for {MicrosoftReportPeriodText(summary)}"
                      + (string.IsNullOrWhiteSpace(summary.MicrosoftReportVersion) ? string.Empty : $", report version {summary.MicrosoftReportVersion}")
                      + ". Licensed users only, tenant-wide."
                    : "Not imported.");
            AddMeta(sheet, "Microsoft 365 usage reports", YesNo(summary.DataSources.M365UsageReportsAvailable),
                summary.DataSources.M365UsageReportDate.HasValue
                    ? $"Daily reports read across the whole period, up to {summary.DataSources.M365UsageReportDate.Value:yyyy-MM-dd}. "
                      + "Per-user figures are an average across the days that user was active."
                    : "Not imported.");
            AddMeta(sheet, "User metadata", YesNo(summary.DataSources.UserMetadataAvailable),
                "Supplies the licensed population and every department breakdown.");
            AddMeta(sheet, "Subscribed SKU inventory", YesNo(summary.SubscribedSkusAvailable),
                summary.SubscribedSkusAvailable
                    ? "Purchased-seat counts came from the tenant's own subscription inventory, so unassigned seats are visible."
                    : "Not imported. Seat figures count ASSIGNED licences only - purchased-but-unassigned seats cannot be seen.");
            AddMeta(sheet, "Tenant conceals user information", YesNo(summary.DataSources.CopilotUsageReportObfuscated),
                "When true, Microsoft's per-user report is unusable; audit-derived figures are unaffected.");

            sheet.AddBlankRow();
            sheet.AddHeaderRow("Threshold used", "Value", "What it controls");
            var o = summary.Options;
            AddMeta(sheet, "Frequency weight", o.FrequencyWeight, "Share of the engagement score from days used.");
            AddMeta(sheet, "Depth weight", o.DepthWeight, "Share from interactions per active day.");
            AddMeta(sheet, "Breadth weight", o.BreadthWeight, "Share from number of Copilot surfaces used.");
            AddMeta(sheet, "Frequency target", o.FrequencyTargetRatio, "Share of working days needed for full marks.");
            AddMeta(sheet, "Depth target", o.DepthTargetInteractionsPerActiveDay, "Interactions per active day for full marks.");
            AddMeta(sheet, "Depth minimum active days", o.DepthMinActiveDays, "Below this many active days the depth component is scaled down in proportion, so one busy afternoon cannot read as a habit.");
            AddMeta(sheet, "Breadth target", o.BreadthTargetApps, "Copilot surfaces for full marks.");
            AddMeta(sheet, "Champion at", o.ChampionScore, "Engagement score for the Champion band.");
            AddMeta(sheet, "Established at", o.EstablishedScore, "The 'habit formed' line - what 'habitual users' counts.");
            AddMeta(sheet, "Developing at", o.DevelopingScore, "Engagement score for the Developing band.");
            AddMeta(sheet, "Habit month length", o.HabitBucketNormalisationDays, "Active days are restated per this many days.");
            AddMeta(sheet, "Licence recommendation at", o.OpportunityRecommendScore, "Business-case score for a recommended candidate.");
            AddMeta(sheet, "Agent review after", $"{o.AgentReviewInactiveDays} days", "Inactivity before an agent is reviewed.");
            AddMeta(sheet, "Agent retire after", $"{o.AgentRetireInactiveDays} days", "Inactivity before an agent is proposed for retirement.");
            AddMeta(sheet, "Agent minimum users", o.AgentMinUsers, "Users an agent needs before its use counts as adoption.");
            AddMeta(sheet, "New-seat activation window", $"{o.ActivationWindowDays} days", "Days from first observed seat assignment to first use for activation-rate reporting.");

            // Null-tolerant like WarningSummary below, not because the summary is built that way but
            // because a workbook that throws on an unexpected null reaches the customer as "Excel found
            // unreadable content" with no clue why.
            if ((summary.Warnings?.Count ?? 0) > 0)
            {
                sheet.AddBlankRow();
                sheet.AddHeaderRow("Warnings affecting these figures", string.Empty, string.Empty);
                foreach (var warning in summary.Warnings)
                {
                    sheet.AddRow(XlsxCell.Wrapped(warning));
                }
            }

            sheet.FreezeTopRows(1);
        }

        private static void AddMeta(XlsxSheet sheet, string name, object value, string notes)
        {
            sheet.AddRow(name, value, XlsxCell.Wrapped(notes));
        }

        /// <summary>
        /// The report period Microsoft's tenant figures describe, in words: its real length and the date it
        /// ends on - never "28 days" for a 30-day report.
        /// </summary>
        private static string MicrosoftReportPeriodText(CopilotAdoptionSummary summary)
        {
            if (!summary.MicrosoftReportDate.HasValue) return "no report period";

            return summary.MicrosoftReportPeriodDays.HasValue
                ? $"the {summary.MicrosoftReportPeriodDays.Value}-day report period to {summary.MicrosoftReportDate.Value:yyyy-MM-dd}"
                : $"the report period to {summary.MicrosoftReportDate.Value:yyyy-MM-dd}";
        }

        /// <summary>
        /// One of Microsoft's tenant figures as a cell: the number, or why there is none. Never a zero for a
        /// figure Microsoft did not report.
        /// </summary>
        private static object MicrosoftReportValue<T>(T? value, CopilotAdoptionSummary summary) where T : struct
        {
            if (value.HasValue) return value.Value;
            return summary.MicrosoftReportDate.HasValue ? "Not reported" : "Not imported";
        }

        /// <summary>
        /// How many licence holders a filtered view selects that the capped licensed-user analysis never
        /// reached - the count its <see cref="CopilotAdoptionWarningKeys.ScopedLicensedUsersNotAnalysed"/>
        /// warning carries - or 0.
        /// </summary>
        private static int LicenceHoldersNotAnalysed(CopilotAdoptionSummary summary)
        {
            var detail = summary.WarningDetails?.FirstOrDefault(d => d.Key == CopilotAdoptionWarningKeys.ScopedLicensedUsersNotAnalysed);
            object count;
            return detail?.Values != null && detail.Values.TryGetValue("count", out count) && count != null
                ? Convert.ToInt32(count, CultureInfo.InvariantCulture)
                : 0;
        }

        /// <summary>
        /// The Report sheet's note on how many users were analysed: all of them, a subset, or all of a slice -
        /// and which slice. The first sheet is the one read on its own, so it must agree with the view's
        /// warnings and with the Headline figures sheet rather than claim the whole tenant was covered.
        /// </summary>
        private static string UsersAnalysedReportNote(CopilotAdoptionSummary summary)
        {
            var notAnalysedInView = LicenceHoldersNotAnalysed(summary);
            if (notAnalysedInView > 0)
            {
                return $"Fewer than the licence holders this filter selects: {notAnalysedInView:N0} more are beyond the "
                    + "analysis limit. Rates in this workbook are of the analysed users only.";
            }

            if (summary.ScoredUsers < summary.LicensedUsers)
            {
                return $"Of {summary.LicensedUsers:N0} licences. Rates in this workbook are of the analysed users only.";
            }

            if (!string.IsNullOrWhiteSpace(FilterDescription(summary)))
            {
                return "Every licensed user matching the filter was analysed - not the whole tenant.";
            }

            return string.IsNullOrWhiteSpace(summary.ScopedEmailDomain)
                ? "Every licensed user was analysed."
                : "Every licensed user on " + summary.ScopedEmailDomain + " was analysed - not the whole tenant.";
        }

        private static string YesNo(bool value)
        {
            return value ? "Yes" : "No";
        }

        private static string WarningSummary(CopilotAdoptionSummary summary)
        {
            if (summary == null) return string.Empty;

            var warnings = new List<string>();
            if (summary.FiguresIncomplete)
            {
                warnings.Add("Figures incomplete: " + string.Join(", ", summary.IncompleteReasons));
            }

            warnings.AddRange(summary.Warnings ?? new List<string>());
            return string.Join(" | ", warnings);
        }

