        /// <summary>
        /// Every tuning option, as a flat <c>key | value</c> list.
        ///
        /// <para>The Report sheet shows the sixteen thresholds a reader is most likely to ask about, and
        /// "How this is calculated" spells the important ones out inside sentences. Neither lets anyone
